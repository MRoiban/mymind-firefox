"""Regenerate patches/firefox.patch from your edits in firefox/.

usage: python3 -I scripts/make-patch.py

Diffs firefox/ against the pristine upstream/chrome-<version>/ it was built
from (manifest.json excluded — it's generated by scripts/firefox-manifest.py).
"""
import difflib, json, os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(root)

version = json.load(open("firefox/manifest.json", encoding="utf-8"))["version"]
base = f"upstream/chrome-{version}"
if not os.path.isdir(base):
    sys.exit(f"error: {base} not found — run scripts/build.sh first")

def files(d):
    out = set()
    for dirpath, _, names in os.walk(d):
        for n in names:
            if not n.startswith("."):
                out.add(os.path.relpath(os.path.join(dirpath, n), d))
    return out

def read(path):
    try:
        with open(path, encoding="utf-8") as f:
            return f.readlines()
    except FileNotFoundError:
        return []
    except UnicodeDecodeError:
        return None  # binary

chunks = []
for rel in sorted((files(base) | files("firefox")) - {"manifest.json"}):
    a, b = read(os.path.join(base, rel)), read(os.path.join("firefox", rel))
    if a is None or b is None:
        if open(os.path.join(base, rel), "rb").read() != open(os.path.join("firefox", rel), "rb").read():
            sys.exit(f"error: binary file changed ({rel}); patches can only carry text changes")
        continue
    if a != b:
        chunks.extend(difflib.unified_diff(a, b, f"a/{rel}", f"b/{rel}"))

with open("patches/firefox.patch", "w", encoding="utf-8") as f:
    f.writelines(chunks)

print(f"patches/firefox.patch updated against {base} ({sum(1 for l in chunks if l.startswith('@@'))} hunks)")
